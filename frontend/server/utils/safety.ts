// Предохранитель по «опасным» темам (препараты, яды, дозировки).
// Вынесено из обработчика чата, чтобы покрывать тестами отдельно.

export const DANGEROUS_TOPIC_RE =
  /(пестицид|гербицид|инсектицид|фунгицид|ядохимикат|отрав|дозиров|концентрац|опрыск|обработ\S*\s+хим|мл\s+на\s+литр)/i;

export const isDangerousTopic = (message: string): boolean =>
  DANGEROUS_TOPIC_RE.test(message || "");

export const SAFETY_NOTE =
  "\nБЕЗОПАСНОСТЬ: запрос касается потенциально опасной темы (препараты/дозировки). НЕ давай дозировок и инструкций по применению химии. Скажи, что таких материалов нет, и направь к профильному специалисту или официальной инструкции препарата.";

/** Дополнение к системному промпту, если запрос потенциально опасен */
export const dangerousTopicNote = (message: string): string =>
  isDangerousTopic(message) ? SAFETY_NOTE : "";
